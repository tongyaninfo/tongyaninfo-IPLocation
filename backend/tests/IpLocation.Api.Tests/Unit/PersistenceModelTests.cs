using System.Net;
using System.Text.Json;
using IpLocation.Api.Data;
using IpLocation.Api.Models.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;

namespace IpLocation.Api.Tests.Unit;

/// <summary>只验证真实 Npgsql 模型与离线 SQL，不建立数据库连接。</summary>
public sealed class PersistenceModelTests
{
    [Fact]
    public void ApprovedNineTablesHaveExplicitSchemaAndComments()
    {
        using var db = CreateContext();
        var entities = db.GetService<IDesignTimeModel>().Model.GetEntityTypes().ToArray();
        Assert.Equal(9, entities.Length);
        foreach (var entity in entities)
        {
            Assert.Equal("iplocation", entity.GetSchema());
            Assert.False(string.IsNullOrWhiteSpace(entity.GetComment()));
            foreach (var property in entity.GetProperties()) Assert.False(string.IsNullOrWhiteSpace(property.GetComment()));
            var id = entity.FindProperty("Id");
            if (id is not null) Assert.Equal(ValueGenerated.Never, id.ValueGenerated);
        }
    }

    [Fact]
    public void PostgreSqlSpecificTypesAndNaturalKeysArePreserved()
    {
        using var db = CreateContext();
        var allowlist = db.Model.FindEntityType(typeof(AdminIpAllowlist))!;
        Assert.Equal("cidr", allowlist.FindProperty(nameof(AdminIpAllowlist.Network))!.GetColumnType());
        var access = db.Model.FindEntityType(typeof(AccessLog))!;
        Assert.Equal("inet", access.FindProperty(nameof(AccessLog.SourceAddress))!.GetColumnType());
        Assert.Equal("jsonb", access.FindProperty(nameof(AccessLog.McpContextJson))!.GetColumnType());
        Assert.True(access.FindProperty(nameof(AccessLog.McpContextJson))!.IsNullable);
        Assert.Equal("timestamp with time zone", access.FindProperty(nameof(AccessLog.OccurredAtUtc))!.GetColumnType());
        Assert.Contains(access.GetIndexes(), index => index.IsUnique && index.Properties.Any(p => p.Name == nameof(AccessLog.EventKey)));
        var activation = db.Model.FindEntityType(typeof(IpDatabaseActivation))!;
        Assert.Equal(["ProviderCode", "AddressFamily"], activation.FindPrimaryKey()!.Properties.Select(p => p.Name).ToArray());
        Assert.True(activation.FindProperty("Revision")!.IsConcurrencyToken);
        Assert.Contains(activation.GetForeignKeys(), key => key.PrincipalEntityType.ClrType == typeof(IpDatabaseVersion) &&
            key.Properties.Select(p => p.Name).SequenceEqual(["VersionId", "ProviderCode"]));
        var aggregate = db.Model.FindEntityType(typeof(TrafficMinuteAggregate))!;
        Assert.Equal(5, aggregate.FindPrimaryKey()!.Properties.Count);
        Assert.Equal("jsonb", aggregate.FindProperty(nameof(TrafficMinuteAggregate.LatencyHistogramJson))!.GetColumnType());
    }

    [Fact]
    public void OfflineCreateSqlHasConstraintsWithoutDatabaseIdentityOrSeedPasswords()
    {
        using var db = CreateContext();
        var sql = db.Database.GenerateCreateScript();
        Assert.Contains("CREATE SCHEMA", sql);
        Assert.Contains("\"ACCESS_LOG\"", sql);
        Assert.Contains("\"EVENT_KEY\"", sql);
        Assert.Contains("CHECK", sql);
        Assert.Contains("FOREIGN KEY", sql);
        Assert.DoesNotContain("GENERATED BY DEFAULT AS IDENTITY", sql, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("INSERT INTO", sql, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void LongIdsAreStringsAndSensitiveEntityFieldsAreNotSerialized()
    {
        var account = new AdminAccount { Id = 9007199254740993, PasswordHash = "sensitive-hash" };
        using var json = JsonDocument.Parse(JsonSerializer.Serialize(account, new JsonSerializerOptions(JsonSerializerDefaults.Web)));
        Assert.Equal("9007199254740993", json.RootElement.GetProperty("id").GetString());
        Assert.False(json.RootElement.TryGetProperty("passwordHash", out _));
        var version = new IpDatabaseVersion { Id = 9007199254740995, StoragePath = "/private/runtime/location" };
        Assert.DoesNotContain("/private/runtime", JsonSerializer.Serialize(version));
    }

    [Fact]
    public void MigrationChainMatchesModelAndProducesIdempotentOfflineSql()
    {
        using var db = CreateContext();
        Assert.Contains(db.Database.GetMigrations(), migration => migration.EndsWith("_InitialBackendStorage", StringComparison.Ordinal));
        Assert.False(db.Database.HasPendingModelChanges());
        var script = db.GetService<IMigrator>().GenerateScript(options: MigrationsSqlGenerationOptions.Idempotent);
        Assert.Contains("IF NOT EXISTS", script);
        Assert.Contains("__EFMigrationsHistory", script);
        Assert.Contains("CREATE TABLE iplocation.\"ACCESS_LOG\"", script);
        Assert.Contains("ADD \"MCP_CONTEXT_JSON\" jsonb", script);
        Assert.DoesNotContain("GENERATED BY DEFAULT AS IDENTITY", script, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void McpContextFiltersTranslateToParameterizedPostgreSqlJsonbWithoutConnecting()
    {
        using var db = CreateContext();
        var toolFilter = JsonSerializer.Serialize(new { toolName = "query_ip\" OR 1=1" });
        var resultFilter = JsonSerializer.Serialize(new { resultCode = "RPC_-32601" });
        var sql = db.AccessLogs.AsNoTracking().Where(item => item.RouteCategory == "mcp" &&
            item.McpContextJson != null && EF.Functions.JsonContains(item.McpContextJson, toolFilter) &&
            EF.Functions.JsonContains(item.McpContextJson, resultFilter)).ToQueryString();
        Assert.Contains("\"MCP_CONTEXT_JSON\" @>", sql);
        // ToQueryString 的参数注释只用于诊断；真正语句必须保留参数占位符，不能拼接任意筛选值。
        var statement = string.Join('\n', sql.Split('\n').Where(line => !line.StartsWith("--", StringComparison.Ordinal)));
        Assert.DoesNotContain("query_ip", statement);
        Assert.DoesNotContain("RPC_-32601", statement);
        Assert.Equal(2, System.Text.RegularExpressions.Regex.Matches(statement,
            "\\\"MCP_CONTEXT_JSON\\\" @> @[A-Za-z0-9_]+").Count);
    }

    internal static IpLocationDbContext CreateContext() => new IpLocationDesignTimeDbContextFactory().CreateDbContext([]);
}
